const clampIndex=(list,index)=>list[Math.max(0,Math.min(list.length-1,Number.isInteger(index)?index:0))];

// 시트 프레임의 손 하나를, drawPlayerSprite 가 그리는 캔버스 좌표(발밑 = 0, 위쪽이 음수, 키 24칸)로 바꾼다.
// geometry 는 drawPlayerSprite 와 같은 값 { frameSize, top, bottom, widthScale } — 없으면 위 표의 값을 쓴다.
// which: 0 = 주 손, 1 = 다른 손. 표에 없는 시트면 null.
export function handAnchor(sheetKey,index,which=0,geometry={}){
 const frames=HAND_ANCHORS[sheetKey];
 if(!frames)return null;
 const hand=clampIndex(frames,index)[which?1:0];
 const bounds=clampIndex(SPRITE_BOUNDS[sheetKey]||[[0,SPRITE_FRAME_SIZE]],index);
 const frameSize=geometry.frameSize||SPRITE_FRAME_SIZE;
 const top=Number.isFinite(geometry.top)?geometry.top:bounds[0];
 const bottom=Number.isFinite(geometry.bottom)?geometry.bottom:bounds[1];
 const scale=PLAYER_HEIGHT/Math.max(1,bottom-top);
 const width=frameSize*scale*(geometry.widthScale??1);
 return {x:(hand[0]/frameSize-.5)*width,y:(hand[1]-bottom)*scale,angle:hand[2],visible:hand[3]===1,scale};
}
export const PLAYER_HEIGHT=24;
